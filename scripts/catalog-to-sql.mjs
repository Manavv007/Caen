#!/usr/bin/env node
/**
 * One-off: turns the original in-code catalogue (packages/commerce/src/catalog.js)
 * into SQL that seeds the Supabase catalogue tables. Output:
 * supabase/seed/catalog.sql. After seeding, edit products in Supabase.
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { CATEGORIES, PRODUCTS } from '../packages/commerce/src/catalog.js';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const url = (img) => (img.local ? `/images/products/${img.local}.webp` : img.src);
const FEATURED = new Set(['celeste-solitaire-ring', 'aurelia-diamond-band', 'mira-diamond-pendant', 'elan-gold-hoops']);

const lines = ['-- Generated by scripts/catalog-to-sql.mjs from the original placeholder catalogue.', 'begin;'];
CATEGORIES.forEach((c, i) => {
  lines.push(`insert into public.categories (slug, name, blurb, image_url, image_alt, sort) values (${[c.slug, c.name, c.blurb, url(c.image), c.image.alt].map(q).join(', ')}, ${i * 10}) on conflict (slug) do nothing;`);
});
PRODUCTS.forEach((p, i) => {
  lines.push(`insert into public.products (sku, slug, name, category, price_inr, label, detail, description, image_url, image_alt, try_on, featured, active, sort) values (${[p.sku, p.slug, p.name, p.category].map(q).join(', ')}, ${p.priceInr}, ${[p.label, p.detail, p.description, url(p.image), p.image.alt, p.tryOn].map(q).join(', ')}, ${FEATURED.has(p.slug)}, true, ${i * 10}) on conflict (sku) do nothing;`);
});
lines.push(`insert into public.site_settings (id, email, phone, whatsapp, free_shipping_above_inr, shipping_fee_inr, return_days) values (1, 'salon@caenjewel.com', '+91 22 4589 0000', '912245890000', 10000, 250, 15) on conflict (id) do nothing;`);
lines.push('commit;', '');
await mkdir(new URL('../supabase/seed/', import.meta.url), { recursive: true });
await writeFile(new URL('../supabase/seed/catalog.sql', import.meta.url), lines.join('\n'));
console.log(`wrote supabase/seed/catalog.sql: ${CATEGORIES.length} categories, ${PRODUCTS.length} products`);
